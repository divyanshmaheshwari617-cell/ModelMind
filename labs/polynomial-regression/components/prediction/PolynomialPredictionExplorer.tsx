
"use client";

import { useMemo, useState } from "react";
import type { TrainingResponse } from "@/lib/api/polynomialApi";

interface Props {
  result: TrainingResponse | null;
  targetName?: string;
}

const fmt = (value: number | null | undefined) =>
  value == null || !Number.isFinite(value)
    ? "—"
    : value.toFixed(5);

export default function PolynomialPredictionExplorer({
  result,
  targetName = "y",
}: Props) {
  const [split, setSplit] = useState<"all" | "train" | "test">("test");
  const [index, setIndex] = useState(0);

  const observations = useMemo(
    () =>
      (result?.predictions ?? []).filter(
        (row) => split === "all" || row.split === split
      ),
    [result, split]
  );

  const safeIndex = Math.min(index, Math.max(0, observations.length - 1));
  const observation = observations[safeIndex];

  const error = observation
    ? observation.actual - observation.predicted
    : 0;

  const absoluteError = Math.abs(error);

  return (
    <section className="space-y-6 rounded-2xl border border-slate-800 bg-slate-900/70 p-6">
      <div>
        <p className="text-xs font-semibold uppercase tracking-widest text-sky-400">
          ModelMind Prediction Studio
        </p>
        <h2 className="mt-2 text-2xl font-bold text-white">
          Interactive Prediction Explorer
        </h2>
        <p className="mt-2 text-sm leading-7 text-slate-400">
          Inspect predictions generated by your trained Python model.
          Understand the inputs, predicted target, actual target,
          and prediction error for individual observations.
        </p>
      </div>

      {!result || observations.length === 0 ? (
        <div className="rounded-xl border border-slate-800 bg-slate-950 p-6 text-sm text-slate-400">
          {!result
            ? "Train a model to explore predictions."
            : "No observations are available for the selected split."}
          {result && (
            <div className="mt-4 flex gap-2">
              {(["all", "train", "test"] as const).map((value) => (
                <button
                  key={value}
                  onClick={() => {
                    setSplit(value);
                    setIndex(0);
                  }}
                  className="rounded-lg border border-slate-700 px-3 py-2 text-xs text-white"
                >
                  {value.toUpperCase()}
                </button>
              ))}
            </div>
          )}
        </div>
      ) : (
        <>
          <div className="flex flex-wrap items-end gap-4">
            <div>
              <label className="block text-xs text-slate-400">
                Dataset split
              </label>
              <select
                value={split}
                onChange={(event) => {
                  setSplit(event.target.value as typeof split);
                  setIndex(0);
                }}
                className="mt-2 rounded-xl border border-slate-700 bg-slate-950 px-4 py-3 text-sm text-white"
              >
                <option value="test">Testing</option>
                <option value="train">Training</option>
                <option value="all">All observations</option>
              </select>
            </div>

            <div className="min-w-[220px] flex-1">
              <label className="block text-xs text-slate-400">
                Observation
              </label>
              <select
                value={safeIndex}
                onChange={(event) => setIndex(Number(event.target.value))}
                className="mt-2 w-full rounded-xl border border-slate-700 bg-slate-950 px-4 py-3 text-sm text-white"
              >
                {observations.map((row, i) => (
                  <option key={i} value={i}>
                    #{i + 1} — {row.split} — actual {fmt(row.actual)}
                  </option>
                ))}
              </select>
            </div>
          </div>

          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
            {[
              { label: `Actual ${targetName}`, value: fmt(observation.actual) },
              { label: `Predicted ${targetName}`, value: fmt(observation.predicted) },
              { label: "Residual (actual − predicted)", value: fmt(error) },
              { label: "Absolute error", value: fmt(absoluteError) },
            ].map((item) => (
              <div
                key={item.label}
                className="rounded-xl border border-slate-800 bg-slate-950 p-4"
              >
                <p className="text-xs text-slate-400">{item.label}</p>
                <p className="mt-3 break-all text-xl font-bold text-white">
                  {item.value}
                </p>
              </div>
            ))}
          </div>

          <div className="rounded-xl border border-slate-800 bg-slate-950 p-5">
            <h3 className="font-semibold text-white">
              Input Features
            </h3>
            <div className="mt-4 grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
              {Object.entries(observation.features).map(([name, value]) => (
                <div
                  key={name}
                  className="rounded-lg border border-slate-800 bg-slate-900 p-3"
                >
                  <p className="text-xs text-slate-400">{name}</p>
                  <p className="mt-1 font-mono text-sky-300">{fmt(value)}</p>
                </div>
              ))}
            </div>
          </div>

          <div className="rounded-xl border border-sky-500/20 bg-sky-500/5 p-5">
            <h3 className="font-semibold text-sky-300">
              Step-by-Step Prediction Explanation
            </h3>

            <div className="mt-4 space-y-3 text-sm leading-7 text-slate-300">
              <p>
                <strong>Step 1:</strong> The model receives the feature
                values shown above.
              </p>
              <p>
                <strong>Step 2:</strong> PolynomialFeatures expands the
                inputs into polynomial powers and interaction terms.
              </p>
              <p>
                <strong>Step 3:</strong> The fitted preprocessing and
                regression pipeline produces the prediction{" "}
                <strong className="text-white">
                  {fmt(observation.predicted)}
                </strong>.
              </p>
              <p>
                <strong>Step 4:</strong> Compare the prediction with the
                actual value {fmt(observation.actual)}.
              </p>
              <p>
                <strong>Step 5:</strong> Residual = actual − predicted
                = <strong className="text-white">{fmt(error)}</strong>.
              </p>
            </div>
          </div>

          <div className="flex flex-wrap gap-3">
            <button
              type="button"
              disabled={safeIndex === 0}
              onClick={() => setIndex((value) => Math.max(0, value - 1))}
              className="rounded-xl border border-slate-700 px-5 py-3 text-sm text-white disabled:opacity-30"
            >
              Previous Observation
            </button>
            <button
              type="button"
              disabled={safeIndex >= observations.length - 1}
              onClick={() =>
                setIndex((value) =>
                  Math.min(observations.length - 1, value + 1)
                )
              }
              className="rounded-xl bg-violet-600 px-5 py-3 text-sm font-medium text-white disabled:opacity-30"
            >
              Next Observation
            </button>
          </div>
        </>
      )}
    </section>
  );
}
